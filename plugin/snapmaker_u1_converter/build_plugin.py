# Strip module-level imports that are satisfied by the shared standard-library
# prelude or by other concatenated core modules. The module bodies remain the
# source of truth, so behavior fixes flow into the packaged plugin on rebuild.

def resource_sources() -> str:
    profiles = {p.name: base64.b64encode(p.read_bytes()).decode("ascii") for p in sorted((PLUGIN / "data" / "profiles").glob("*.3mf"))}
    rules = {p.name: json.loads(p.read_text(encoding="utf-8")) for p in sorted((PLUGIN / "data" / "rules").glob("*.json"))}
    return "EMBEDDED_PROFILES = " + repr(profiles) + "\nEMBEDDED_RULES = " + repr(rules) + "\n"


def module_sources() -> str:
    blocks = []
    for name in MODULES:
        source = (BACKEND / name).read_text(encoding="utf-8")
        if name == "rules_engine.py":
            source = source.replace("import yaml", "import json")
            source = source.replace("from models import RuleDefinition, RuleMatch", "from core_models import RuleDefinition, RuleMatch, RuleMatchConditions")
            source = source.replace("yaml.safe_load(path.read_text(encoding=\"utf-8\"))", "json.loads(path.read_text(encoding=\"utf-8\"))")
            source = source.replace("except yaml.YAMLError as err:", "except json.JSONDecodeError as err:")
            source = source.replace("invalid YAML", "invalid JSON")
            source = source.replace("rule = RuleDefinition(**raw)", "rule = RuleDefinition(name=str(raw[\"name\"]), description=str(raw.get(\"description\", \"\")), match=RuleMatchConditions(**(raw.get(\"match\") or {})), overrides=dict(raw.get(\"overrides\") or {}), priority=int(raw.get(\"priority\", 0)), enabled=bool(raw.get(\"enabled\", True)), source_path=str(path))")
            source = source.replace("return rule.model_copy(update={\"source_path\": str(path)})", "return rule")
            source = source.replace("p.suffix.lower() not in (\".yaml\", \".yml\")", "p.suffix.lower() != \".json\"")
            source = source.replace("*.yaml``/``*.yml", "*.json``")
            source = source.replace("Each rule is one YAML file", "Each rule is one JSON file")
            source = source.replace("Parse a single YAML rule file", "Parse a single JSON rule file")
        blocks.append(f"{name[:-3]!r}: {source!r}")
    return "_EMBEDDED_MODULES = {\n" + ",\n".join(blocks) + "\n}\n"


